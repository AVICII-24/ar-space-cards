// Prepares the app for offline use. Run after changing any file: npm run build
//  1. draws the app icons (no image tools needed)
//  2. writes precache.js: the list of files the service worker stores on the tablet,
//     with a version stamp so tablets pick up the new files on their next online visit.
import { readdirSync, readFileSync, writeFileSync, statSync, mkdirSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { deflateSync } from 'node:zlib';
import { join } from 'node:path';

// ---------- icons ----------
function png(size, pixel) {
  const raw = Buffer.alloc((size * 4 + 1) * size);
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    let r = 0, g = 0, b = 0;
    for (const [dx, dy] of [[0.25, 0.25], [0.75, 0.25], [0.25, 0.75], [0.75, 0.75]]) {      // 2x2 anti-aliasing
      const c = pixel((x + dx) / size, (y + dy) / size); r += c[0]; g += c[1]; b += c[2];
    }
    raw.set([r / 4, g / 4, b / 4, 255], y * (size * 4 + 1) + 1 + x * 4);
  }
  const crcTable = Array.from({ length: 256 }, (_, n) => { let c = n; for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1; return c >>> 0; });
  const crc = buf => { let c = 0xffffffff; for (const v of buf) c = crcTable[(c ^ v) & 255] ^ (c >>> 8); return (c ^ 0xffffffff) >>> 0; };
  const chunk = (type, data) => { const len = Buffer.alloc(4); len.writeUInt32BE(data.length); const body = Buffer.concat([Buffer.from(type), data]); const sum = Buffer.alloc(4); sum.writeUInt32BE(crc(body)); return Buffer.concat([len, body, sum]); };
  const head = Buffer.alloc(13); head.writeUInt32BE(size, 0); head.writeUInt32BE(size, 4); head.set([8, 6, 0, 0, 0], 8);
  return Buffer.concat([Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]), chunk('IHDR', head), chunk('IDAT', deflateSync(raw, { level: 9 })), chunk('IEND', Buffer.alloc(0))]);
}
const mix = (a, b, t) => a.map((v, i) => v + (b[i] - v) * t);
function icon(u, v) {                                    // a ringed planet on a night sky
  let c = mix([16, 26, 68], [7, 11, 31], v);
  const x = u - 0.5, y = v - 0.5, a = -0.42, rx = x * Math.cos(a) - y * Math.sin(a), ry = x * Math.sin(a) + y * Math.cos(a);
  const ring = Math.hypot(rx / 0.4, ry / 0.11), inRing = ring < 1 && ring > 0.74, d = Math.hypot(x, y);
  if (inRing && ry < 0) c = [255, 211, 77];                                       // far half of the ring, behind the planet
  if (d < 0.235) c = mix([255, 240, 200], [245, 158, 11], Math.min(Math.hypot(x + 0.08, y + 0.08) / 0.32, 1));
  if (inRing && ry >= 0) c = [255, 211, 77];                                      // near half, in front
  return c;
}
mkdirSync('assets', { recursive: true });
for (const s of [192, 512]) writeFileSync(`assets/icon-${s}.png`, png(s, icon));
writeFileSync('assets/icon.svg', `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><defs><linearGradient id="b" x1="0" y1="0" x2="0" y2="1"><stop offset="0" stop-color="#101a44"/><stop offset="1" stop-color="#070b1f"/></linearGradient><radialGradient id="p" cx="0.35" cy="0.35" r="0.8"><stop offset="0" stop-color="#fff0c8"/><stop offset="1" stop-color="#f59e0b"/></radialGradient></defs><rect width="100" height="100" fill="url(#b)"/><g transform="rotate(-24 50 50)"><path d="M10 50a40 11 0 0 1 80 0" fill="none" stroke="#ffd34d" stroke-width="5"/><circle cx="50" cy="50" r="23.5" fill="url(#p)"/><path d="M10 50a40 11 0 0 0 80 0" fill="none" stroke="#ffd34d" stroke-width="5"/></g></svg>\n`);

// ---------- precache list ----------
const files = ['index.html', 'print.html', 'manifest.webmanifest'];
const walk = dir => { for (const f of readdirSync(dir)) { const p = join(dir, f); if (statSync(p).isDirectory()) walk(p); else if (!/LICENSE|\.DS_Store/.test(f)) files.push(p.split('\\').join('/')); } };
['css', 'js', 'content', 'vendor', 'assets'].forEach(walk);
const hash = createHash('sha1'); for (const f of files) hash.update(f).update(readFileSync(f));
const version = hash.digest('hex').slice(0, 10);
writeFileSync('precache.js', `// Generated by tools/build.mjs. Do not edit.\nself.APP_VERSION = '${version}';\nself.APP_FILES = ${JSON.stringify(['./', ...files.map(f => './' + f)], null, 1)};\n`);
console.log(`icons written · ${files.length} files in offline list · version ${version}`);
